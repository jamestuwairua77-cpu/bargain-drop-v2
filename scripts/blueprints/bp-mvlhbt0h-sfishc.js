var params = new URLSearchParams(window.location.search);
var token = (params.get('token') || '').trim();
var emailParam = (params.get('email') || '').trim();

function showErr(m) {
  var e = document.getElementById('error-msg');
  e.textContent = m;
  e.style.display = 'block';
  var s = document.getElementById('success-msg');
  s.style.display = 'none';
}

function showOk(m) {
  var s = document.getElementById('success-msg');
  s.textContent = m;
  s.style.display = 'block';
  var e = document.getElementById('error-msg');
  e.style.display = 'none';
}

function toggleVis(id) {
  var el = document.getElementById(id);
  if (!el) return;
  el.type = el.type === 'password' ? 'text' : 'password';
}

function setRuleState(id, passed, text) {
  var el = document.getElementById(id);
  if (!el) return;
  el.textContent = (passed ? '✓ ' : '○ ') + text;
  el.style.color = passed ? '#49a66a' : '#818181';
  el.style.fontWeight = passed ? '700' : '500';
}

function evaluateStrength() {
  var p = document.getElementById('password').value || '';
  var hasLen = p.length >= 10 && p.length <= 128;
  var hasUpper = /[A-Z]/.test(p);
  var hasLower = /[a-z]/.test(p);
  var hasNum = /[0-9]/.test(p);
  var hasSym = /[^A-Za-z0-9]/.test(p);

  setRuleState('rule-len', hasLen, 'At least 10 characters');
  setRuleState('rule-upper', hasUpper, 'One uppercase letter (A–Z)');
  setRuleState('rule-lower', hasLower, 'One lowercase letter (a–z)');
  setRuleState('rule-num', hasNum, 'One number (0–9)');
  setRuleState('rule-sym', hasSym, 'One special symbol (!@#$%^&*)');

  return hasLen && hasUpper && hasLower && hasNum && hasSym;
}

(function verifyTokenOnMount() {
  var badge = document.getElementById('token-badge');
  var reqLink = document.getElementById('request-new-link');
  var submitBtn = document.getElementById('submit');

  if (!token || !/^[a-f0-9]{64}$/i.test(token)) {
    showErr('Invalid or missing password reset token in URL. Please request a fresh 1-hour reset link.');
    if (reqLink) reqLink.style.display = 'block';
    if (submitBtn) submitBtn.disabled = true;
    return;
  }

  if (emailParam) {
    document.getElementById('subtitle').textContent = 'Setting new password for ' + emailParam;
  }

  fetch('/api/forgot-password', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ action: 'verify', token: token, email: emailParam })
  })
    .then(function(r) { return r.json(); })
    .then(function(d) {
      if (d && d.valid) {
        if (badge) {
          var mins = Math.max(1, Math.ceil((d.remainingSeconds || 3600) / 60));
          badge.style.display = 'block';
          badge.innerHTML = '🔒 Verified 256-Bit Recovery Token · Expires in <strong style="color:#fe3442;">' + mins + ' mins</strong>';
        }
        if (d.email && !emailParam) {
          emailParam = d.email;
          document.getElementById('subtitle').textContent = 'Setting new password for ' + d.email;
        }
      } else if (d && d.error) {
        showErr(d.error);
        if (reqLink) reqLink.style.display = 'block';
        if (submitBtn) submitBtn.disabled = true;
      }
    })
    .catch(function() {});
})();

function handleReset() {
  if (!token || !/^[a-f0-9]{64}$/i.test(token)) {
    showErr('Invalid or missing reset link. Please request a new one.');
    return;
  }
  var p = document.getElementById('password').value;
  var c = document.getElementById('confirm').value;

  if (!evaluateStrength()) {
    showErr('Please satisfy all 5 password strength requirements above.');
    return;
  }
  if (p !== c) {
    showErr('Passwords do not match. Please re-enter carefully.');
    return;
  }

  var btn = document.getElementById('submit');
  btn.disabled = true;
  btn.textContent = 'Updating Password…';

  fetch('/api/forgot-password', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ action: 'reset', token: token, password: p, newPassword: p, email: emailParam })
  })
    .then(function(r) { return r.json(); })
    .then(function(d) {
      if (d && (d.success || d.ok)) {
        // Clear token from browser URL bar immediately so it cannot be bookmarked or leaked
        try {
          window.history.replaceState(null, '', window.location.pathname);
        } catch (e) {}
        token = '';
        showOk('✓ Password updated and recovery token invalidated! Redirecting to Sign In…');
        btn.disabled = true;
        btn.textContent = 'Password Updated ✓';
        var redirectUrl = 'sign-in.html?reset=1';
        var targetEmail = (d && d.email) || emailParam;
        if (targetEmail) {
          redirectUrl += '&email=' + encodeURIComponent(targetEmail);
        }
        setTimeout(function() {
          window.location.href = redirectUrl;
        }, 1600);
      } else {
        btn.disabled = false;
        btn.textContent = 'Update Password';
        showErr(d && (d.error || d.message) ? (d.error || d.message) : 'Could not reset password.');
        if (d && String(d.error || '').toLowerCase().indexOf('expired') !== -1) {
          var reqLink = document.getElementById('request-new-link');
          if (reqLink) reqLink.style.display = 'block';
        }
      }
    })
    .catch(function() {
      btn.disabled = false;
      btn.textContent = 'Update Password';
      showErr('Network error while contacting authentication server. Please try again.');
    });
}
